"""UUIDv7 generation.

Every primary key in this system is a UUIDv7 (time-ordered), generated
application-side — per the PostgreSQL Database Design's Identifier
Strategy (Section 1): it preserves B-tree insert locality (unlike
UUIDv4) while staying non-enumerable, and needs no database round-trip
or extension to produce.

Implemented locally, with no new dependency, because Python's stdlib
`uuid` module doesn't gain `uuid.uuid7()` until 3.14 — this project's
floor is 3.12 (see backend/pyproject.toml). This is a standard,
straightforward implementation of the RFC 9562 layout: a 48-bit
millisecond timestamp, a 4-bit version, a 2-bit variant, and the
remaining 74 bits random.
"""

import os
import threading
import time
import uuid

# RFC 9562 §6.2 method 1: the 12-bit rand_a field is a counter within one
# millisecond, so IDs generated by this process are strictly increasing —
# rows inserted together (a question and its answer, a document's chunks)
# sort in creation order by primary key.
_lock = threading.Lock()
_last_ms = 0
_counter = 0
_COUNTER_MAX = 0xFFF


def generate_uuid7() -> uuid.UUID:
    """Generate one UUIDv7 identifier, monotonic within this process."""
    global _last_ms, _counter
    with _lock:
        now_ms = int(time.time() * 1000)
        if now_ms > _last_ms:
            _last_ms = now_ms
            # Random start leaves headroom for many IDs in the same millisecond.
            _counter = int.from_bytes(os.urandom(2), "big") & 0x7FF
        else:
            _counter += 1
            if _counter > _COUNTER_MAX:
                # Counter exhausted (or the clock went backwards): borrow the next ms.
                _last_ms += 1
                _counter = 0
        unix_ts_ms, counter = _last_ms, _counter

    rand = os.urandom(8)
    uuid_bytes = bytearray(16)
    uuid_bytes[0:6] = unix_ts_ms.to_bytes(6, byteorder="big")
    uuid_bytes[6] = 0x70 | (counter >> 8)  # version 7 + high 4 bits of counter
    uuid_bytes[7] = counter & 0xFF  # low 8 bits of counter
    uuid_bytes[8] = 0x80 | (rand[0] & 0x3F)  # variant 10xxxxxx + 6 random bits
    uuid_bytes[9:16] = rand[1:8]  # 56 random bits
    return uuid.UUID(bytes=bytes(uuid_bytes))
